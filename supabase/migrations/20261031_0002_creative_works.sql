-- 기존 books 테이블과 장르 enum을 변경하지 않고 회원 작품을 독립적으로 관리합니다.
create table if not exists public.creative_works (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 title varchar(200) not null check (length(trim(title)) between 1 and 200),
 pen_name varchar(100) not null check (length(trim(pen_name)) between 1 and 100),
 category text not null check (category in ('novel','poetry','essay','children','other')),
 description text not null default '',
 content text not null default '',
 status text not null default 'draft' check (status in ('draft','pending','published','rejected','hidden')),
 review_note text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 published_at timestamptz
);
create index if not exists creative_works_user_idx on public.creative_works(user_id);
create index if not exists creative_works_status_idx on public.creative_works(status, published_at desc);
alter table public.creative_works enable row level security;
-- 이 테이블은 서버의 인증된 tRPC API에서만 서비스 키를 통해 접근합니다.
-- 브라우저의 publishable/anon 키에는 테이블 직접 접근 권한을 주지 않습니다.
revoke all on public.creative_works from anon, authenticated;
revoke all on sequence public.creative_works_id_seq from anon, authenticated;
