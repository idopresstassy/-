-- 명작무료책방(korealib) 신규 Supabase PostgreSQL 스키마
-- Supabase Dashboard > SQL Editor에서 전체를 실행합니다.

create extension if not exists pgcrypto;

create type public.book_genre as enum ('classic', 'modern', 'foreign');
create type public.user_role as enum ('user', 'admin');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text,
  email text,
  role public.user_role not null default 'user',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_signed_in_at timestamptz not null default now()
);

create table public.books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null,
  genre public.book_genre not null,
  content text,
  description text,
  cover_url text,
  youtube_url text,
  audio_url text,
  webtoon_url text,
  source_url text,
  table_of_contents text,
  study_material text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.donation_info (
  id bigint generated by default as identity primary key,
  bank_name text,
  account_number text,
  account_holder text,
  description text,
  email text,
  representative text,
  closing_message text,
  legal_notice text,
  updated_at timestamptz not null default now()
);

create table public.bookmarks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  page integer not null,
  label text,
  created_at timestamptz not null default now()
);

create table public.reading_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  current_page integer not null default 0,
  total_pages integer not null default 0,
  updated_at timestamptz not null default now(),
  unique (user_id, book_id)
);

create table public.bookshelf (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (user_id, book_id)
);

create table public.book_views (
  id bigint generated by default as identity primary key,
  book_id bigint not null references public.books(id) on delete cascade,
  viewer_id text not null,
  user_id uuid references public.profiles(id) on delete set null,
  viewed_at timestamptz not null default now(),
  unique (book_id, viewer_id)
);

create table public.visits (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  session_id text,
  visited_at timestamptz not null default now()
);

create index books_genre_idx on public.books (genre);
create index book_views_book_idx on public.book_views (book_id);
create index visits_visited_at_idx on public.visits (visited_at desc);
create index reading_progress_book_idx on public.reading_progress (book_id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

create trigger books_set_updated_at
before update on public.books
for each row execute function public.set_updated_at();

create trigger donation_info_set_updated_at
before update on public.donation_info
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, name, email)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'name', new.raw_user_meta_data ->> 'full_name'),
    new.email
  )
  on conflict (id) do update set
    name = excluded.name,
    email = excluded.email,
    last_signed_in_at = now();
  return new;
end;
$$;

create trigger auth_user_profile_trigger
after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.books enable row level security;
alter table public.donation_info enable row level security;
alter table public.bookmarks enable row level security;
alter table public.reading_progress enable row level security;
alter table public.bookshelf enable row level security;
alter table public.book_views enable row level security;
alter table public.visits enable row level security;

-- 공개 도서관 콘텐츠는 누구나 읽을 수 있습니다.
create policy "Public can read books" on public.books for select using (true);
create policy "Public can read donation information" on public.donation_info for select using (true);

-- 로그인 사용자는 자신의 읽기 기록과 서재만 관리합니다.
create policy "Users can read own profile" on public.profiles for select using (auth.uid() = id);
create policy "Users can update own profile" on public.profiles for update using (auth.uid() = id);
create policy "Users manage own bookmarks" on public.bookmarks for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage own progress" on public.reading_progress for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage own bookshelf" on public.bookshelf for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- 비로그인 방문자 집계는 서버(Render)에서 service_role로 기록합니다.
-- 클라이언트에서 visits 및 book_views 직접 입력은 허용하지 않습니다.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'book-covers',
  'book-covers',
  true,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do nothing;

create policy "Public can read book covers"
on storage.objects for select
using (bucket_id = 'book-covers');

-- 관리자 업로드는 브라우저가 아니라 서버(Render)의 service_role로 수행합니다.
