-- 회원 창작 원고 접수와 관리자 검수를 위한 추가 스키마.
create type public.creative_work_genre as enum (
  'short_story',
  'romance',
  'fantasy',
  'wuxia',
  'mystery',
  'other'
);

alter table public.books
  add column creative_genre public.creative_work_genre;

alter table public.books
  add constraint books_creative_genre_required
  check ((genre = 'creative' and creative_genre is not null) or (genre <> 'creative' and creative_genre is null));

create table public.creative_submissions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 200),
  author_name text not null check (char_length(author_name) between 1 and 120),
  genre public.creative_work_genre not null,
  description text check (description is null or char_length(description) <= 2000),
  content text not null check (char_length(content) between 1 and 500000),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  review_note text check (review_note is null or char_length(review_note) <= 2000),
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  published_book_id bigint references public.books(id) on delete set null,
  rights_confirmed_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint creative_submissions_review_state_check check (
    (status = 'pending' and reviewed_at is null and published_book_id is null)
    or (status = 'approved' and reviewed_at is not null)
    or (status = 'rejected' and reviewed_at is not null and published_book_id is null)
  )
);

create index creative_submissions_user_created_idx
  on public.creative_submissions (user_id, created_at desc);
create index creative_submissions_pending_idx
  on public.creative_submissions (created_at asc) where status = 'pending';

create trigger creative_submissions_set_updated_at
before update on public.creative_submissions
for each row execute function public.set_updated_at();

alter table public.creative_submissions enable row level security;

create policy "Authors can read their own creative submissions"
  on public.creative_submissions for select to authenticated
  using (auth.uid() = user_id);

comment on table public.creative_submissions is
  '회원이 제출한 창작 원고. 공개 도서로 등록되기 전까지 관리자만 전체 원고를 검수한다.';
